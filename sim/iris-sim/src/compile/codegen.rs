    use crate::parser::ast::{Port, PortDirection, Signal};

    #[test]
    fn test_codegen_basic() {
        let module = Module {
            name: "Counter".to_string(),
            generics: vec![],
            ports: vec![
                Port {
                    name: "clk".to_string(),
                    direction: PortDirection::In,
                    ty: Type::Clock,
                },
                Port {
                    name: "rst".to_string(),
                    direction: PortDirection::In,
                    ty: Type::Reset { active_low: false },
                },
                Port {
                    name: "enable".to_string(),
                    direction: PortDirection::In,
                    ty: Type::Bit,
                },
                Port {
                    name: "count".to_string(),
                    direction: PortDirection::Out,
                    ty: Type::BitVec { width: 8 },
                },
            ],
            signals: vec![Signal {
                name: "counter".to_string(),
                ty: Type::BitVec { width: 8 },
                init_value: Some(Expression::Literal(Literal::Decimal {
                    width: Some(8),
                    value: 0,
                })),
                is_mutable: true,
                is_var: true,
            }],
            logic_blocks: vec![],
            instances: vec![],
            span: None,
            is_test: false,
            seq_blocks: vec![],
            initial_blocks: vec![],
            fsm_blocks: vec![],
            memories: vec![],
        };

        let mut gen = RustCodeGenerator::new();
        let result = gen.generate(&module);
        assert!(result.is_ok());
        let code = result.unwrap();
        assert!(code.contains("fn main()"));
        assert!(code.contains("Clock::new"));
        assert!(code.contains("WaveTracer::new"));
    }
