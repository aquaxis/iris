    /// Generate wave tracer setup
    fn generate_test_tracer_setup(&mut self, test_mod: &Module) -> Result<(), CodeGenError> {
        self.writeln("// Wave tracer setup");
        self.writeln("let mut tracer = WaveTracer::new();");
        self.writeln("tracer.register(\"clk\", 1);");
        self.writeln("tracer.register(\"rst\", 1);");

        // Test signals
        for signal in &test_mod.signals {
            if matches!(signal.ty, Type::Clock | Type::Reset { .. }) {
                continue;
            }
            let width = self.type_to_width(&signal.ty);
            self.writeln(&format!("tracer.register(\"{}\", {});", signal.name, width));
        }

        // Collect DUT signal info first (to avoid borrow issues)
        let mut dut_signals: Vec<(String, String, usize)> = Vec::new();
        for inst in &test_mod.instances {
            if let Some(dut) = self.dut_modules.get(&inst.module_name) {
                for signal in &dut.signals {
                    let width = self.type_to_width(&signal.ty);
                    dut_signals.push((inst.name.clone(), signal.name.clone(), width));
                }
                for port in &dut.ports {
                    if matches!(port.ty, Type::Clock | Type::Reset { .. }) {
                        continue;
                    }
                    let width = self.type_to_width(&port.ty);
                    dut_signals.push((inst.name.clone(), port.name.clone(), width));
                }
            }
        }

        // Write DUT signal registrations
        for (inst_name, sig_name, width) in dut_signals {
            self.writeln(&format!(
                "tracer.register(\"{}.{}\", {});",
                inst_name, sig_name, width
            ));
        }

        self.writeln("");
        Ok(())
    }

