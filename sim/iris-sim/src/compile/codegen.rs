    /// Generate main simulation loop
    fn generate_test_simulation_loop(&mut self, test_mod: &Module) -> Result<(), CodeGenError> {
        self.writeln("// Main simulation loop");
        self.writeln("for _cycle in 0..cycles {");
        self.indent += 1;

        self.writeln("clk.tick(); // Rising edge");
        self.writeln("");

        // Posedge evaluation
        self.writeln("if clk.posedge() {");
        self.indent += 1;

        // Update DUT input ports from test signals
        self.writeln("// Update DUT inputs");
        for inst in &test_mod.instances {
            for (port_name, expr) in &inst.port_connections {
                if let Some(dut) = self.dut_modules.get(&inst.module_name) {
                    // Check if port is input
                    if let Some(port) = dut.ports.iter().find(|p| &p.name == port_name) {
                        if matches!(port.direction, PortDirection::In) {
                            if !matches!(port.ty, Type::Clock | Type::Reset { .. }) {
                                let expr_code = self.generate_expression(expr, false)?;
                                self.writeln(&format!("{}.{} = {};", inst.name, port_name, expr_code));
                            }
                        }
                    }
                }
            }
        }
        self.writeln("");

        // DUT posedge
        self.writeln("// DUT sequential logic");
        for inst in &test_mod.instances {
            self.writeln(&format!("{}.posedge(rst.is_active());", inst.name));
        }
        self.writeln("");

        // Test sync block
        self.writeln("// Test sequential logic");
        self.writeln("if !rst.is_active() {");
        self.indent += 1;
        for block in &test_mod.logic_blocks {
            if let LogicBlock::Sync(sync) = block {
                for stmt in &sync.statements {
                    self.generate_test_statement(stmt, test_mod)?;
                }
            }
        }
        self.indent -= 1;
        self.writeln("}");

        self.indent -= 1;
        self.writeln("}");
        self.writeln("");

        // DUT combinational logic
        self.writeln("// DUT combinational logic");
        for inst in &test_mod.instances {
            self.writeln(&format!("{}.comb();", inst.name));
        }
        self.writeln("");

        // Test combinational logic
        self.writeln("// Test combinational logic");
        for block in &test_mod.logic_blocks {
            if let LogicBlock::Comb(comb) = block {
                for stmt in &comb.statements {
                    self.generate_test_statement(stmt, test_mod)?;
                }
            }
        }
        self.writeln("");

        // Record values
        self.generate_test_value_recording(test_mod)?;

        self.writeln("clk.tick(); // Falling edge");

        self.indent -= 1;
        self.writeln("}");
        self.writeln("");

        Ok(())
    }

    /// Generate a statement for test module
    fn generate_test_statement(&mut self, stmt: &Statement, test_mod: &Module) -> Result<(), CodeGenError> {
        match stmt {
            Statement::Assign { target, value } => {
                let value_code = self.generate_test_expression(value, test_mod)?;

                // Find signal width for masking
                if let Some((_, width)) = self.signals.iter().find(|(n, _)| n == target) {
                    if *width < 64 {
                        let mask = self.width_to_mask(*width);
                        self.writeln(&format!("{} = ({}) & {};", target, value_code, mask));
                    } else {
                        self.writeln(&format!("{} = {};", target, value_code));
                    }
                } else {
                    self.writeln(&format!("{} = {};", target, value_code));
                }
            }
            Statement::If {
                condition,
                then_branch,
                else_branch,
            } => {
                let cond_code = self.generate_test_expression(condition, test_mod)?;
                // Check if condition is already a boolean expression
                let cond_str = if self.is_boolean_expression(condition) {
                    cond_code
                } else {
                    format!("{} != 0", cond_code)
                };
                self.writeln(&format!("if {} {{", cond_str));
                self.indent += 1;
                for s in then_branch {
                    self.generate_test_statement(s, test_mod)?;
                }
                self.indent -= 1;
                if let Some(else_stmts) = else_branch {
                    self.writeln("} else {");
                    self.indent += 1;
                    for s in else_stmts {
                        self.generate_test_statement(s, test_mod)?;
                    }
                    self.indent -= 1;
                }
                self.writeln("}");
            }
            Statement::Match { .. } => {
                return Err(CodeGenError::UnsupportedFeature("match statement".to_string()));
            }
            Statement::For { var, range, body } => {
                let start = self.generate_test_expression(&range.start, test_mod)?;
                let end = self.generate_test_expression(&range.end, test_mod)?;
                let range_op = if range.inclusive { "..=" } else { ".." };
                self.writeln(&format!("for {} in {}{}{} {{", var, start, range_op, end));
                self.indent += 1;
                for s in body {
                    self.generate_test_statement(s, test_mod)?;
                }
                self.indent -= 1;
                self.writeln("}");
            }
            Statement::While { condition, body } => {
                let cond_code = self.generate_test_expression(condition, test_mod)?;
                self.writeln(&format!("while {} != 0 {{", cond_code));
                self.indent += 1;
                for s in body {
                    self.generate_test_statement(s, test_mod)?;
                }
                self.indent -= 1;
                self.writeln("}");
            }
        }
        Ok(())
    }

    /// Generate expression for test module (handles hierarchical references)
    fn generate_test_expression(&self, expr: &Expression, test_mod: &Module) -> Result<String, CodeGenError> {
        match expr {
            Expression::Literal(lit) => self.generate_literal(lit),
            Expression::Ident(name) => {
                // Check if it's a hierarchical reference like "dut.count"
                if name.contains('.') {
                    Ok(name.replace('.', "."))
                } else {
                    Ok(name.clone())
                }
            }
            Expression::BinOp { op, lhs, rhs } => {
                let lhs_code = self.generate_test_expression(lhs, test_mod)?;
                let rhs_code = self.generate_test_expression(rhs, test_mod)?;
                let op_str = self.binop_to_rust(op);
                Ok(format!("({} {} {})", lhs_code, op_str, rhs_code))
            }
            Expression::UnaryOp { op, expr } => {
                let expr_code = self.generate_test_expression(expr, test_mod)?;
                let op_str = self.unaryop_to_rust(op);
                Ok(format!("({}{})", op_str, expr_code))
            }
            Expression::Index { base, index } => {
                let base_code = self.generate_test_expression(base, test_mod)?;
                let index_code = self.generate_test_expression(index, test_mod)?;
                Ok(format!("(({} >> {}) & 1)", base_code, index_code))
            }
            Expression::Slice { base, high, low } => {
                let base_code = self.generate_test_expression(base, test_mod)?;
                let width = high - low + 1;
                let mask = (1u64 << width) - 1;
                Ok(format!("(({} >> {}) & 0x{:x})", base_code, low, mask))
            }
            Expression::MethodCall { receiver, method, args: _ } => {
                let recv_code = self.generate_test_expression(receiver, test_mod)?;
                match method.as_str() {
                    "posedge" | "negedge" => Ok(format!("{}.{}()", recv_code, method)),
                    // Hierarchical signal access (e.g., dut.count)
                    _ => Ok(format!("{}.{}", recv_code, method)),
                }
            }
            Expression::If { condition, then_expr, else_expr } => {
                let cond_code = self.generate_test_expression(condition, test_mod)?;
                let then_code = self.generate_test_expression(then_expr, test_mod)?;
                let else_code = self.generate_test_expression(else_expr, test_mod)?;
                // Check if condition is already a boolean expression
                let cond_str = if self.is_boolean_expression(condition) {
                    cond_code
                } else {
                    format!("{} != 0", cond_code)
                };
                Ok(format!("if {} {{ {} }} else {{ {} }}", cond_str, then_code, else_code))
            }
            Expression::Concat(exprs) => {
                let mut result = String::new();
                let mut shift = 0;
                for (i, e) in exprs.iter().rev().enumerate() {
                    let e_code = self.generate_test_expression(e, test_mod)?;
                    if i == 0 {
                        result = e_code;
                    } else {
                        shift += 8;
                        result = format!("(({} << {}) | ({}))", e_code, shift, result);
                    }
                }
                Ok(result)
            }
            Expression::MemRead { mem_name, addr } => {
                let _ = (mem_name, addr);
                Err(CodeGenError::UnsupportedFeature("memory read".to_string()))
            }
        }
    }

    /// Generate expression (for DUT, with optional self prefix)
